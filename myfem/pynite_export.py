"""Generate and run a standalone PyNite script from a MyFEM JSON model."""

import argparse
import json
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from string import Template

PYTHON_TEMPLATE = Template('''# AI created the file
# Author: MyFEM generator
# Copyright, License: GPLv3
# Created: $created_date

# Last Changes:
# YYYY-MM-DD HH:mm CET: Author: Changes
# $created_time: MyFEM: Generated this PyNite model from JSON

"""Standalone PyNite model generated by MyFEM."""

from contextlib import redirect_stdout
import json
from pathlib import Path

from Pynite import FEModel3D

MODEL_DATA = json.loads($model_data)
OUTPUT_LOG = Path($output_log)


def build_model() -> FEModel3D:
    model = FEModel3D()

    for node in MODEL_DATA["nodes"]:
        model.add_node(node["id"], node["x"], node["y"], node["z"])

    for material in MODEL_DATA["materials"]:
        model.add_material(
            material["id"],
            material["E"],
            material["G"],
            material["nu"],
            material["rho"],
        )

    for section in MODEL_DATA["sections"]:
        model.add_section(
            section["id"],
            section["A"],
            section["I_yy"],
            section["I_zz"],
            section["I_T"],
        )

    for member in MODEL_DATA["members"]:
        model.add_member(
            member["id"],
            member["node_start"],
            member["node_end"],
            member["material"],
            member["section"],
        )

    for support in MODEL_DATA["supports"]:
        model.def_support(
            support["node"],
            support["DX"],
            support["DY"],
            support["DZ"],
            support["RX"],
            support["RY"],
            support["RZ"],
        )

    for load in MODEL_DATA["loads"]:
        if load["type"] != "member_distributed":
            raise ValueError(f"Unsupported load type: {load['type']!r}")
        model.add_member_dist_load(
            load["member"],
            load["direction"],
            load["value_start"],
            load["value_end"],
            load["position_start"],
            load["position_end"],
            case=load["case"],
        )

    for combination in MODEL_DATA["load_combinations"]:
        model.add_load_combo(combination["id"], combination["cases"])

    return model


def print_results(model: FEModel3D) -> None:
    for combination in MODEL_DATA["load_combinations"]:
        combination_id = combination["id"]
        print(f"=== RESULTS: {combination_id} ===")
        print("--- Support reactions ---")
        for support in MODEL_DATA["supports"]:
            node_id = support["node"]
            node = model.nodes[node_id]
            print(
                f"{node_id}: FX={node.RxnFX[combination_id] / 1000:.2f} kN, "
                f"FZ={node.RxnFZ[combination_id] / 1000:.2f} kN"
            )

        print("--- Member results ---")
        for member_data in MODEL_DATA["members"]:
            member_id = member_data["id"]
            member = model.members[member_id]
            print(f"{member_id}:")
            print(
                f"  My max/min: {member.max_moment('My', combination_id) / 1000:.2f} / "
                f"{member.min_moment('My', combination_id) / 1000:.2f} kNm"
            )
            print(
                f"  Fz max/min: {member.max_shear('Fz', combination_id) / 1000:.2f} / "
                f"{member.min_shear('Fz', combination_id) / 1000:.2f} kN"
            )
            print(
                f"  dz max: {member.max_deflection('dz', combination_id) * 1000:.2f} mm"
            )
        print()


def main() -> None:
    with OUTPUT_LOG.open("w", encoding="utf-8") as log_file:
        with redirect_stdout(log_file):
            model = build_model()
            model.analyze(check_statics=True)
            print_results(model)


if __name__ == "__main__":
    main()
''')


def generate_python_script(model_path: Path, python_path: Path, log_path: Path) -> None:
    """Write a standalone PyNite Python script for a MyFEM JSON model."""
    data = json.loads(model_path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError("The model JSON must contain a top-level object")
    if not data.get("load_combinations"):
        raise ValueError("The model JSON must define at least one load combination")

    now = datetime.now().astimezone()
    model_data = json.dumps(data, allow_nan=False, separators=(",", ":"))
    source = PYTHON_TEMPLATE.substitute(
        created_date=now.strftime("%Y-%m-%d"),
        created_time=now.strftime("%Y-%m-%d %H:%M %Z"),
        output_log=repr(str(log_path)),
        model_data=repr(model_data),
    )
    python_path.write_text(source, encoding="utf-8")


def generate_and_run(model_path: Path, python_path: Path, log_path: Path) -> None:
    """Generate a standalone PyNite script and run it to write the result log."""
    generate_python_script(model_path, python_path, log_path)
    subprocess.run([sys.executable, str(python_path)], check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path, help="MyFEM JSON model")
    parser.add_argument(
        "--python",
        type=Path,
        help="Generated Python path (defaults to the model path with a .py suffix)",
    )
    parser.add_argument(
        "--log",
        type=Path,
        default=Path("output.log"),
        help="Result log path (defaults to output.log in the current directory)",
    )
    args = parser.parse_args()
    python_path = args.python or args.model.with_suffix(".py")
    try:
        generate_and_run(args.model, python_path, args.log)
    except (OSError, TypeError, ValueError, subprocess.CalledProcessError) as error:
        parser.error(str(error))

    print(f"Generated PyNite script: {python_path}")
    print(f"Saved solver results: {args.log}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
