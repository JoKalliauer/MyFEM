def _result_scales(model: FEModel3D) -> dict[str, float]:
    force_values = []
    moment_values = []
    length_values = []
    for combination in MODEL_DATA["load_combinations"]:
        combination_id = combination["id"]
        for node in model.nodes.values():
            force_values.extend(
                getattr(node, field)[combination_id]
                for field in ("RxnFX", "RxnFY", "RxnFZ")
            )
            moment_values.extend(
                getattr(node, field)[combination_id]
                for field in ("RxnMX", "RxnMY", "RxnMZ")
            )
            length_values.extend(
                getattr(node, field)[combination_id] for field in ("DX", "DY", "DZ")
            )

        for member_data in MODEL_DATA["members"]:
            member = model.members[member_data["id"]]
            force_values.extend(
                (member.max_axial(combination_id), member.min_axial(combination_id))
            )
            for direction in ("Fy", "Fz"):
                force_values.extend(
                    (
                        member.max_shear(direction, combination_id),
                        member.min_shear(direction, combination_id),
                    )
                )
            for direction in ("My", "Mz"):
                moment_values.extend(
                    (
                        member.max_moment(direction, combination_id),
                        member.min_moment(direction, combination_id),
                    )
                )
            for direction in ("dx", "dy", "dz"):
                length_values.extend(
                    (
                        member.max_deflection(direction, combination_id),
                        member.min_deflection(direction, combination_id),
                    )
                )

    return {
        "force": max((abs(value) for value in force_values), default=0.0),
        "moment": max((abs(value) for value in moment_values), default=0.0),
        "length": max((abs(value) for value in length_values), default=0.0),
    }


def _below_precision(value: float, scale: float) -> bool:
    precision = MODEL_DATA["precision"]
    threshold = max(
        precision["absolute"], precision["relative"] * scale
    )
    return abs(value) < threshold


def _format_result(value: float, scale: float, divisor: float = 1000.0) -> str:
    value = 0.0 if _below_precision(value, scale) else value
    displayed = value / divisor
    if abs(displayed) < 0.005:
        displayed = 0.0
    return f"{displayed:.2f}"


def _normalize_statics_output(
    output: str, scales: dict[str, float]
) -> str:
    lines = output.splitlines(keepends=True)
    headers = None
    for index, line in enumerate(lines):
        if "Sum FX" in line and "|" in line:
            headers = [cell.strip() for cell in line.split("|")[1:-1]]
            continue
        if headers is None or not line.startswith("|"):
            continue

        ending = "\\n" if line.endswith("\\n") else ""
        cells = line.rstrip("\\r\\n").split("|")
        if len(cells) != len(headers) + 2:
            continue
        for cell_index, header in enumerate(headers, 1):
            if cell_index == 1:
                continue
            cell = cells[cell_index]
            try:
                value = float(cell.strip())
            except ValueError:
                continue
            result_type = (
                "moment"
                if header.startswith(("Sum M", "Sum RM"))
                else "force"
            )
            if _below_precision(value, scales[result_type]):
                cells[cell_index] = f"{'0':^{len(cell)}}"
        lines[index] = "|".join(cells) + ending
    return "".join(lines)


