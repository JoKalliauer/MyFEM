def _migrate_model_data(data: dict[str, object]) -> dict[str, object]:
    model_version = data.get("format_version", 1)
    if isinstance(model_version, bool) or not isinstance(model_version, (int, float)):
        raise TypeError("Model format_version must be a number")
    current_float_version = isinstance(model_version, float) and model_version == 0.1
    if not current_float_version and not (
        isinstance(model_version, int) and model_version in (1, 2)
    ):
        raise ValueError(f"Unsupported model format version {model_version}")

    migrated = dict(data)
    defaults = {
        "materials": {"auto_generated": False},
        "sections": {"auto_generated": False},
        "members": {
            "material_was_default": False,
            "section_was_default": False,
        },
        "load_combinations": {"generated_default": False},
    }
    for collection, metadata in defaults.items():
        records = data.get(collection, [])
        if not isinstance(records, list):
            raise TypeError(f"Model {collection} must be a list")
        upgraded_records: list[dict[str, object]] = []
        for record in records:
            if not isinstance(record, dict):
                raise TypeError(f"Each model {collection} item must be an object")
            upgraded_records.append(
                {
                    **record,
                    **{key: record.get(key, value) for key, value in metadata.items()},
                }
            )
        migrated[collection] = upgraded_records
    migrated["format_version"] = 0.1
    return migrated


def _ensure_precision(data: dict[str, object]) -> dict[str, object]:
    if "precision" not in data:
        precision: dict[str, object] = {
            "absolute": 0.0,
            "relative": 1e-12,
            "defaulted": True,
        }
    else:
        precision_data = data["precision"]
        if not isinstance(precision_data, dict):
            raise TypeError("Model precision must be an object")
        precision = dict(precision_data)

    for key, default in (("absolute", 0.0), ("relative", 1e-12)):
        value = precision.get(key, default)
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise TypeError(f"Model precision {key!r} must be a number")
        if not math.isfinite(value) or value < 0:
            raise ValueError(f"Model precision {key!r} must be finite and non-negative")
        precision[key] = float(value)

    defaulted = precision.get("defaulted", True)
    if not isinstance(defaulted, bool):
        raise TypeError("Model precision 'defaulted' must be a boolean")
    precision["defaulted"] = defaulted

    upgraded = dict(data)
    upgraded["precision"] = precision
    return upgraded


def _ensure_default_combination(data: dict[str, object]) -> dict[str, object]:
    combinations = data.get("load_combinations", [])
    if not isinstance(combinations, list):
        raise TypeError("Model load_combinations must be a list")
    if combinations:
        return data

    loads = data.get("loads", [])
    if not isinstance(loads, list):
        raise TypeError("Model loads must be a list")
    load_cases: set[str] = set()
    for load in loads:
        if not isinstance(load, dict) or not isinstance(load.get("case"), str):
            raise TypeError("Each model load must specify a string load case")
        load_cases.add(load["case"])
    other_cases = sorted(load_cases - {"default"})
    if other_cases:
        raise ValueError(
            "No load combination is defined. The default SLS combination can "
            "only be generated for load case 'default'; found: "
            f"{', '.join(other_cases)}"
        )

    upgraded = dict(data)
    upgraded["load_combinations"] = [
        {
            "id": "SLS",
            "cases": {"default": 1.0},
            "generated_default": True,
        }
    ]
    return upgraded


def _strip_combination_metadata(
    data: dict[str, object],
) -> tuple[dict[str, object], str]:
    combinations = data.get("load_combinations")
    if not isinstance(combinations, list):
        raise TypeError("Model load_combinations must be a list")
    python_combinations: list[dict[str, object]] = []
    generated_default = False
    for combination in combinations:
        if not isinstance(combination, dict):
            raise TypeError("Each load combination must be an object")
        generated_default |= combination.get("generated_default") is True
        python_combinations.append(
            {
                key: value
                for key, value in combination.items()
                if key != "generated_default"
            }
        )

    python_data = dict(data)
    python_data["load_combinations"] = python_combinations
    comment = (
        "# MyFEM generated the default SLS combination (default=1).\n"
        if generated_default
        else ""
    )
    return python_data, comment


def generate_python_script(model_path: Path, python_path: Path, log_path: Path) -> None:
    """Write a standalone PyNite Python script for a MyFEM JSON model."""
    data = json.loads(model_path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError("The model JSON must contain a top-level object")
    data = _migrate_model_data(data)
    data = _ensure_precision(data)
    data = _ensure_default_combination(data)
    data, combination_comment = _strip_combination_metadata(data)

    now = datetime.now().astimezone()
    model_data = json.dumps(data, allow_nan=False, separators=(",", ":"))
    source = PYTHON_TEMPLATE.substitute(
        created_date=now.strftime("%Y-%m-%d"),
        created_time=now.strftime("%Y-%m-%d %H:%M %Z"),
        output_log=repr(str(log_path)),
        model_data=repr(model_data),
        combination_comment=combination_comment,
    )
    python_path.write_text(source, encoding="utf-8")


def generate_and_run(model_path: Path, python_path: Path, log_path: Path) -> None:
    """Generate a standalone PyNite script and run it to write the result log."""
    generate_python_script(model_path, python_path, log_path)
    subprocess.run([sys.executable, str(python_path)], check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model", type=Path, help="MyFEM JSON model")
    parser.add_argument(
        "--python",
        type=Path,
        help="Generated Python path (defaults to the model path with a .py suffix)",
    )
    parser.add_argument(
        "--log",
        type=Path,
        help="Result path (defaults to the model path with a .out suffix)",
    )
    args = parser.parse_args()
    python_path = args.python or args.model.with_suffix(".py")
    log_path = args.log or args.model.with_suffix(".out")
    try:
        generate_and_run(args.model, python_path, log_path)
    except (OSError, TypeError, ValueError, subprocess.CalledProcessError) as error:
        parser.error(str(error))

    print(f"Generated PyNite script: {python_path}")
    print(f"Saved solver results: {log_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
